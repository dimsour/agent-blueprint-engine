/** Pipes inside a cell would end it; the descriptions do not use them, but the test does not care. */
function cell(text: string): string {
  return text.replace(/\|/g, '\\|')
}

export function renderOptionsDoc(): string {
  const lines: string[] = [
    OPTIONS_DOC_START,
    '',
    'Every fixed choice a form offers, with what choosing it does. The same text is shown beside each option in the app; both come from `packages/core/src/model/options.ts`.',
  ]
  for (const name of Object.keys(OPTION_TABLES) as (keyof typeof OPTION_TABLES)[]) {
    const [values, info] = OPTION_TABLES[name]
    lines.push('', `#### ${HEADINGS[name]}`, '', '| Value | Label | Means |', '| --- | --- | --- |')
    for (const value of values) {
      const entry = (info as Readonly<Record<string, { label: string; description: string }>>)[
        value
      ]
      if (!entry) continue
      lines.push(`| \`${value}\` | ${cell(entry.label)} | ${cell(entry.description)} |`)
    }
  }
  lines.push('', OPTIONS_DOC_END)
  return lines.join('\n')
}

/** The document with the generated section replaced, or appended when the markers are absent. */
export function withOptionsDoc(document: string): string {
  const rendered = renderOptionsDoc()
  const start = document.indexOf(OPTIONS_DOC_START)
  const end = document.indexOf(OPTIONS_DOC_END)
  if (start >= 0 && end > start) {
    return document.slice(0, start) + rendered + document.slice(end + OPTIONS_DOC_END.length)
  }
  return `${document.trimEnd()}\n\n## Options reference\n\n${rendered}\n`
}
