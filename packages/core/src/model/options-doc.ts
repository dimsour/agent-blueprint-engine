/**
 * The options reference, rendered for docs/02 (P9-21).
 *
 * Generated rather than written, because a table of a hundred and forty rows that is typed by
 * hand is a table that is wrong somewhere within a month. `scripts/options-doc.ts` writes it
 * between two markers in docs/02-domain-model.md, and `tests/options.test.ts` fails when the
 * document no longer matches what this produces — so the doc, the dropdowns and the schema
 * cannot say three different things.
 *
 * Pure: a string from the tables, with no IO, so the test can call it.
 */
import { OPTION_TABLES } from './options'

// The prettier range markers are part of the block: the tables are generated in a fixed
// shape, and a formatter that re-pads them would leave the document one format run away from
// failing the test that checks it.
export const OPTIONS_DOC_START = [
  '<!-- options:start — generated by `pnpm --filter @agent-blueprint/core options:doc`; do not edit by hand -->',
  '<!-- prettier-ignore-start -->',
].join('\n')
export const OPTIONS_DOC_END = ['<!-- prettier-ignore-end -->', '<!-- options:end -->'].join('\n')

